package api

import (
	"net/http"

	accessperm "campfire/internal/shared/permissions"
)

// Handler builds the versioned application routes.
func (a *API) Handler() http.Handler {
	mux := http.NewServeMux()
	platform := func(pattern, permission string, handler http.HandlerFunc) {
		mux.HandleFunc(pattern, a.platformPermission(permission, handler))
	}
	server := func(pattern, permission string, handler http.HandlerFunc) {
		mux.HandleFunc(pattern, a.serverPermission(permission, handler))
	}

	mux.HandleFunc("GET /api/v1/auth/session", a.authSession)
	mux.HandleFunc("POST /api/v1/auth/setup", a.authSetup)
	mux.HandleFunc("POST /api/v1/auth/login", a.authLogin)
	mux.HandleFunc("POST /api/v1/auth/logout", a.authLogout)
	mux.HandleFunc("POST /api/v1/auth/view-as", a.startViewAs)
	mux.HandleFunc("DELETE /api/v1/auth/view-as", a.stopViewAs)
	mux.HandleFunc("GET /api/v1/auth/oidc/start", a.oidcStart)
	mux.HandleFunc("GET /api/v1/auth/oidc/callback", a.oidcCallback)
	mux.HandleFunc("POST /api/v1/auth/oidc/link", a.oidcLink)
	mux.HandleFunc("GET /api/v1/permissions", a.permissionCatalog)
	mux.HandleFunc("GET /api/v1/tokens", a.listAPITokens)
	mux.HandleFunc("GET /api/v1/notifications", a.notificationsEnabled(a.listNotifications))
	mux.HandleFunc("GET /api/v1/notifications/unread", a.notificationsEnabled(a.unreadNotifications))
	mux.HandleFunc("PUT /api/v1/notifications/{notificationID}/read", a.notificationsEnabled(a.readNotification))
	mux.HandleFunc("POST /api/v1/notifications/read-all", a.notificationsEnabled(a.readAllNotifications))
	platform("GET /api/v1/notifications/status", accessperm.NotificationsManage, a.notificationsEnabled(a.notificationStatus))
	platform("POST /api/v1/notifications/test", accessperm.NotificationsManage, a.notificationsEnabled(a.testNotification))
	platform("POST /api/v1/notifications/retry-deliveries", accessperm.NotificationsManage, a.notificationsEnabled(a.retryNotificationDeliveries))
	mux.HandleFunc("POST /api/v1/tokens", a.createAPIToken)
	mux.HandleFunc("DELETE /api/v1/tokens/{tokenID}", a.revokeAPIToken)
	mux.HandleFunc("GET /api/v1/schedules", a.activityEnabled(a.listSchedules))
	mux.HandleFunc("POST /api/v1/schedules", a.activityEnabled(a.saveSchedule))
	mux.HandleFunc("POST /api/v1/schedules/preview", a.activityEnabled(a.previewSchedule))
	mux.HandleFunc("PUT /api/v1/schedules/{scheduleID}", a.activityEnabled(a.saveSchedule))
	mux.HandleFunc("PATCH /api/v1/schedules/{scheduleID}", a.activityEnabled(a.setScheduleEnabled))
	mux.HandleFunc("DELETE /api/v1/schedules/{scheduleID}", a.activityEnabled(a.deleteSchedule))
	mux.HandleFunc("POST /api/v1/schedules/{scheduleID}/run", a.activityEnabled(a.runSchedule))
	mux.HandleFunc("GET /api/v1/schedules/executions", a.activityEnabled(a.listExecutions))
	mux.HandleFunc("POST /api/v1/schedules/executions/{runID}/retry", a.activityEnabled(a.retryExecution))
	platform("GET /api/v1/audit", accessperm.AuditView, a.activityEnabled(a.listAudit))
	platform("GET /api/v1/backups", accessperm.ServersManageAll, a.listBackups)
	platform("POST /api/v1/sparks", accessperm.SparksManage, a.createSpark)
	platform("GET /api/v1/sparks", accessperm.SparksManage, a.listSparks)
	platform("GET /api/v1/sparks/access-options", accessperm.SparksManage, a.sparkAccessOptions)
	platform("GET /api/v1/sparks/update-status", accessperm.SparksManage, a.sparkUpdateStatus)
	platform("POST /api/v1/sparks/{id}/update", accessperm.SparksManage, a.updateSparkClient)
	platform("POST /api/v1/sparks/{id}/prune", accessperm.SparksManage, a.pruneSpark)
	platform("GET /api/v1/sparks/{id}", accessperm.SparksManage, a.getSpark)
	platform("GET /api/v1/sparks/{id}/metrics/history", accessperm.SparksManage, a.sparkResourceHistory)
	platform("PATCH /api/v1/sparks/{id}", accessperm.SparksManage, a.updateSpark)
	platform("DELETE /api/v1/sparks/{id}", accessperm.SparksManage, a.deleteSpark)
	platform("POST /api/v1/sparks/{id}/enrollment", accessperm.SparksManage, a.createSparkEnrollment)
	platform("GET /api/v1/sparks/{id}/roles", accessperm.SparksManage, a.sparkRoles)
	platform("PUT /api/v1/sparks/{id}/roles", accessperm.SparksManage, a.setSparkRoles)
	platform("GET /api/v1/sparks/{id}/access", accessperm.SparksManage, a.sparkAccess)
	platform("POST /api/v1/sparks/{id}/access/grants", accessperm.SparksManage, a.grantSparkAccess)
	platform("DELETE /api/v1/sparks/{id}/access/grants/{grantID}", accessperm.SparksManage, a.removeSparkAccess)
	platform("GET /api/v1/embers", accessperm.EmbersManage, a.listEmbers)
	platform("GET /api/v1/embers/updates", accessperm.EmbersManage, a.listEmberUpdates)
	platform("POST /api/v1/embers/{id}/check-update", accessperm.EmbersManage, a.checkEmberUpdate)
	platform("POST /api/v1/embers/{id}/download-update", accessperm.EmbersManage, a.downloadEmberUpdate)
	platform("POST /api/v1/embers", accessperm.EmbersManage, a.importEmber)
	platform("PUT /api/v1/embers/{id}", accessperm.EmbersManage, a.importEmber)
	platform("POST /api/v1/embers/preview", accessperm.EmbersManage, a.previewEmber)
	platform("POST /api/v1/embers/preview-url", accessperm.EmbersManage, a.previewEmberURL)
	platform("GET /api/v1/embers/{id}", accessperm.EmbersManage, a.getEmber)
	platform("DELETE /api/v1/embers/{id}", accessperm.EmbersManage, a.deleteEmber)
	platform("GET /api/v1/users", accessperm.UsersManage, a.listUsers)
	platform("POST /api/v1/users", accessperm.UsersManage, a.createUser)
	platform("PUT /api/v1/users/{userID}", accessperm.UsersManage, a.updateUser)
	platform("DELETE /api/v1/users/{userID}", accessperm.UsersManage, a.deleteUser)
	platform("GET /api/v1/roles", accessperm.RolesManage, a.listRoles)
	platform("POST /api/v1/roles", accessperm.RolesManage, a.createRole)
	platform("PUT /api/v1/roles/{roleID}", accessperm.RolesManage, a.updateRole)
	platform("DELETE /api/v1/roles/{roleID}", accessperm.RolesManage, a.deleteRole)
	platform("GET /api/v1/provisioning", accessperm.ServersCreate, a.provisioning)
	platform("GET /api/v1/provisioning/access", accessperm.ServersCreate, a.serverAccessOptions)
	mux.HandleFunc("GET /api/v1/servers", a.listServers)
	mux.HandleFunc("GET /api/v1/monitoring", a.monitoring)
	server("GET /api/v1/servers/{id}/metrics", accessperm.ServerView, a.serverMetrics)
	server("GET /api/v1/servers/{id}/events", accessperm.ServerView, a.gameEvents)
	server("GET /api/v1/servers/{id}/events/{event}/media/{attachment}", accessperm.ServerView, a.gameMedia)
	server("GET /api/v1/servers/{id}/metrics/history", accessperm.ServerView, a.serverResourceHistory)
	platform("POST /api/v1/servers", accessperm.ServersCreate, a.createServer)
	server("GET /api/v1/servers/{id}", accessperm.ServerView, a.getServer)
	server("PUT /api/v1/servers/{id}", accessperm.ServerConfigure, a.updateServer)
	server("DELETE /api/v1/servers/{id}", accessperm.ServerDelete, a.deleteServer)
	server("GET /api/v1/servers/{id}/editor", accessperm.ServerConfigure, a.serverEditor)
	mux.HandleFunc("GET /api/v1/servers/{id}/access", a.serverOwner(a.serverAccess))
	mux.HandleFunc("POST /api/v1/servers/{id}/access/grants", a.serverOwner(a.grantServerAccess))
	mux.HandleFunc("DELETE /api/v1/servers/{id}/access/grants/{grantID}", a.serverOwner(a.removeServerAccess))
	mux.HandleFunc("POST /api/v1/servers/{id}/members", a.serverOwner(a.shareServer))
	mux.HandleFunc("DELETE /api/v1/servers/{id}/members/{userID}", a.serverOwner(a.unshareServer))
	platform("PUT /api/v1/servers/{id}/owner", accessperm.ServersManageAll, a.transferServer)
	platform("POST /api/v1/servers/{id}/ember", accessperm.ServersManageAll, a.applyServerEmber)
	platform("GET /api/v1/servers/{id}/transfers", accessperm.SparksManage, a.platformPermission(accessperm.ServersManageAll, a.listTransfers))
	platform("POST /api/v1/servers/{id}/transfers", accessperm.SparksManage, a.platformPermission(accessperm.ServersManageAll, a.beginTransfer))
	platform("POST /api/v1/transfers/{transferID}/retry", accessperm.SparksManage, a.platformPermission(accessperm.ServersManageAll, a.retryTransfer))
	platform("POST /api/v1/transfers/{transferID}/cancel", accessperm.SparksManage, a.platformPermission(accessperm.ServersManageAll, a.cancelTransfer))
	server("POST /api/v1/servers/{id}/configuration", accessperm.ServerOperate, a.syncServerConfiguration)
	server("POST /api/v1/servers/{id}/actions", accessperm.ServerView, a.serverAction)
	server("GET /api/v1/servers/{id}/status", accessperm.ServerView, a.serverStatus)
	server("GET /api/v1/servers/{id}/console", accessperm.ServerConsoleRead, a.serverConsole)
	server("GET /api/v1/servers/{id}/console/stream", accessperm.ServerConsoleRead, a.streamConsole)
	server("POST /api/v1/servers/{id}/console", accessperm.ServerConsoleWrite, a.serverConsole)
	server("GET /api/v1/servers/{id}/files", accessperm.ServerFilesRead, a.serverFiles)
	server("GET /api/v1/servers/{id}/files/limits", accessperm.ServerFilesWrite, a.fileLimits)
	server("POST /api/v1/servers/{id}/files", accessperm.ServerView, a.serverFiles)
	server("GET /api/v1/servers/{id}/files/download", accessperm.ServerFilesRead, a.downloadFile)
	server("GET /api/v1/servers/{id}/backups", accessperm.ServerBackupsRead, a.serverBackups)
	server("GET /api/v1/servers/{id}/backup-policy", accessperm.ServerConfigure, a.getBackupPolicy)
	server("PUT /api/v1/servers/{id}/backup-policy", accessperm.ServerConfigure, a.saveBackupPolicy)
	server("DELETE /api/v1/servers/{id}/backups/{name}", accessperm.ServerBackupsDelete, a.deleteBackup)
	server("GET /api/v1/servers/{id}/backups/{name}", accessperm.ServerBackupsDownload, a.downloadBackup)

	return a.auditRequests(a.authenticate(mux))
}
