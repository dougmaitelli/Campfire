package api

import "net/http"

// Handler builds the versioned application routes.
func (a *API) Handler() http.Handler {
	mux := http.NewServeMux()
	platform := func(pattern, permission string, handler http.HandlerFunc) {
		mux.HandleFunc(pattern, a.platformPermission(permission, handler))
	}
	server := func(pattern, permission string, handler http.HandlerFunc) {
		mux.HandleFunc(pattern, a.serverPermission(permission, handler))
	}

	mux.HandleFunc("GET /api/v1/auth/session", a.authSession)
	mux.HandleFunc("POST /api/v1/auth/setup", a.authSetup)
	mux.HandleFunc("POST /api/v1/auth/login", a.authLogin)
	mux.HandleFunc("POST /api/v1/auth/logout", a.authLogout)
	mux.HandleFunc("GET /api/v1/auth/oidc/start", a.oidcStart)
	mux.HandleFunc("GET /api/v1/auth/oidc/callback", a.oidcCallback)
	mux.HandleFunc("POST /api/v1/auth/oidc/link", a.oidcLink)
	mux.HandleFunc("GET /api/v1/schedules", a.activityEnabled(a.listSchedules))
	mux.HandleFunc("POST /api/v1/schedules", a.activityEnabled(a.saveSchedule))
	mux.HandleFunc("PUT /api/v1/schedules/{scheduleID}", a.activityEnabled(a.saveSchedule))
	mux.HandleFunc("DELETE /api/v1/schedules/{scheduleID}", a.activityEnabled(a.deleteSchedule))
	mux.HandleFunc("POST /api/v1/schedules/{scheduleID}/run", a.activityEnabled(a.runSchedule))
	mux.HandleFunc("GET /api/v1/schedules/executions", a.activityEnabled(a.listExecutions))
	mux.HandleFunc("POST /api/v1/schedules/executions/{runID}/retry", a.activityEnabled(a.retryExecution))
	platform("GET /api/v1/audit", "audit.view", a.activityEnabled(a.listAudit))
	platform("POST /api/v1/sparks", "sparks.manage", a.createSpark)
	platform("GET /api/v1/sparks", "sparks.manage", a.listSparks)
	platform("GET /api/v1/sparks/{id}", "sparks.manage", a.getSpark)
	platform("PATCH /api/v1/sparks/{id}", "sparks.manage", a.updateSpark)
	platform("DELETE /api/v1/sparks/{id}", "sparks.manage", a.deleteSpark)
	platform("POST /api/v1/sparks/{id}/enrollment", "sparks.manage", a.createSparkEnrollment)
	platform("GET /api/v1/sparks/{id}/roles", "sparks.manage", a.sparkRoles)
	platform("PUT /api/v1/sparks/{id}/roles", "sparks.manage", a.setSparkRoles)
	platform("GET /api/v1/embers", "embers.manage", a.listEmbers)
	platform("POST /api/v1/embers", "embers.manage", a.importEmber)
	platform("POST /api/v1/embers/preview", "embers.manage", a.previewEmber)
	platform("POST /api/v1/embers/preview-url", "embers.manage", a.previewEmberURL)
	platform("GET /api/v1/embers/{id}", "embers.manage", a.getEmber)
	platform("GET /api/v1/users", "users.manage", a.listUsers)
	platform("POST /api/v1/users", "users.manage", a.createUser)
	platform("PUT /api/v1/users/{userID}", "users.manage", a.updateUser)
	platform("DELETE /api/v1/users/{userID}", "users.manage", a.deleteUser)
	platform("GET /api/v1/roles", "roles.manage", a.listRoles)
	platform("POST /api/v1/roles", "roles.manage", a.createRole)
	platform("PUT /api/v1/roles/{roleID}", "roles.manage", a.updateRole)
	platform("DELETE /api/v1/roles/{roleID}", "roles.manage", a.deleteRole)
	platform("GET /api/v1/provisioning", "servers.create", a.provisioning)
	mux.HandleFunc("GET /api/v1/servers", a.listServers)
	mux.HandleFunc("GET /api/v1/monitoring", a.monitoring)
	server("GET /api/v1/servers/{id}/metrics", "server.view", a.serverMetrics)
	platform("POST /api/v1/servers", "servers.create", a.createServer)
	server("GET /api/v1/servers/{id}", "server.view", a.getServer)
	server("PUT /api/v1/servers/{id}", "server.configure", a.updateServer)
	server("DELETE /api/v1/servers/{id}", "server.delete", a.deleteServer)
	server("GET /api/v1/servers/{id}/editor", "server.configure", a.serverEditor)
	server("GET /api/v1/servers/{id}/access", "server.share", a.serverAccess)
	server("POST /api/v1/servers/{id}/members", "server.share", a.shareServer)
	server("DELETE /api/v1/servers/{id}/members/{userID}", "server.share", a.unshareServer)
	platform("PUT /api/v1/servers/{id}/owner", "servers.manage_all", a.transferServer)
	platform("GET /api/v1/servers/{id}/transfers", "sparks.manage", a.platformPermission("servers.manage_all", a.listTransfers))
	platform("POST /api/v1/servers/{id}/transfers", "sparks.manage", a.platformPermission("servers.manage_all", a.beginTransfer))
	platform("POST /api/v1/transfers/{transferID}/retry", "sparks.manage", a.platformPermission("servers.manage_all", a.retryTransfer))
	platform("POST /api/v1/transfers/{transferID}/cancel", "sparks.manage", a.platformPermission("servers.manage_all", a.cancelTransfer))
	server("POST /api/v1/servers/{id}/configuration", "server.operate", a.syncServerConfiguration)
	server("POST /api/v1/servers/{id}/actions", "server.operate", a.serverAction)
	server("GET /api/v1/servers/{id}/status", "server.view", a.serverStatus)
	server("GET /api/v1/servers/{id}/console", "server.operate", a.serverConsole)
	server("GET /api/v1/servers/{id}/console/stream", "server.operate", a.streamConsole)
	server("POST /api/v1/servers/{id}/console", "server.operate", a.serverConsole)
	server("GET /api/v1/servers/{id}/files", "server.operate", a.serverFiles)
	server("POST /api/v1/servers/{id}/files", "server.operate", a.serverFiles)
	server("GET /api/v1/servers/{id}/backups", "server.operate", a.serverBackups)
	server("GET /api/v1/servers/{id}/backups/{name}", "server.operate", a.downloadBackup)

	return a.auditRequests(a.authenticate(mux))
}
